# Generates app/src/main/java/com/example/kelma216/data/content/PhotoManifest.kt
# from tools/photo_manifest.json. Run after source_photos.ps1 and after copying the
# images into app/src/main/res/drawable.
#
# Usage: powershell -ExecutionPolicy Bypass -File tools/generate_manifest.kt.ps1

$ErrorActionPreference = "Stop"
$manifestPath = Join-Path $PSScriptRoot "photo_manifest.json"
$outPath = Join-Path (Split-Path -Parent $PSScriptRoot) "app\src\main\java\com\example\kelma216\data\content\PhotoManifest.kt"

$entries = Get-Content $manifestPath -Raw | ConvertFrom-Json
$seen = @{}
$rows = @()
foreach ($e in $entries) {
    if ($seen.ContainsKey($e.answer)) { continue }
    $seen[$e.answer] = $true
    $rows += $e
}

function Esc($s) {
    if ($null -eq $s) { return $null }
    return ($s -replace '\\', '\\' -replace '"', '\"' -replace "`r?`n", ' ')
}

$q = [char]34
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("package com.example.kelma216.data.content")
$lines.Add("")
$lines.Add("import com.example.kelma216.R")
$lines.Add("")
$lines.Add("/**")
$lines.Add(" * Look-up table of clue photos downloaded and attributed by tools/source_photos.ps1.")
$lines.Add(" * THIS FILE IS GENERATED by tools/generate_manifest.kt.ps1 - do not edit by hand.")
$lines.Add(" *")
$lines.Add(" * An answer missing here has no photo yet: the puzzle stays playable and shows a")
$lines.Add(" * text prompt. Nothing is fabricated.")
$lines.Add(" */")
$lines.Add("object PhotoManifest {")
$lines.Add("")
$lines.Add("    private val assets: Map<String, PhotoAsset> = mapOf(")
foreach ($r in $rows) {
    $artist = Esc $r.artist
    $artistArg = if ($artist) { (", artist = " + $q + $artist + $q) } else { "" }
    $lines.Add("        " + $q + $r.answer + $q + " to PhotoAsset(")
    $lines.Add("            answer = " + $q + $r.answer + $q + ",")
    $lines.Add("            drawableRes = R.drawable." + $r.drawableName + ",")
    $lines.Add("            sourceUrl = " + $q + (Esc $r.sourceUrl) + $q + ",")
    $lines.Add("            license = " + $q + (Esc $r.license) + $q + $artistArg + ",")
    $lines.Add("        ),")
}
$lines.Add("    )")
$lines.Add("")
$lines.Add("    fun forAnswer(answer: String): PhotoAsset? = assets[answer.uppercase()]")
$lines.Add("")
$lines.Add("    val withPhotoCount: Int get() = assets.size")
$lines.Add("")
$lines.Add("    fun hasPhoto(answer: String): Boolean = assets.containsKey(answer.uppercase())")
$lines.Add("}")

Set-Content -Path $outPath -Value ($lines -join "`r`n") -Encoding UTF8
Write-Host ("Wrote {0} photo entries -> {1}" -f $rows.Count, $outPath)
